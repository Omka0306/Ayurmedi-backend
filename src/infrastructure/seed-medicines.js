async function seed() {
  const now = new Date().toISOString();
  let created = 0, skipped = 0;

  for (const [num, nameMr, typeMarathi, price] of medicines) {
    const medicineType = typeMap[typeMarathi] || typeMarathi;
    const item = {
      medicine_id: uuidv4(),
      hospital_id: 'GLOBAL',
      name_mr: nameMr,
      name_en: nameMr, // Use Marathi as default for name_en too
      medicine_type: medicineType,
      medicine_type_mr: typeMarathi, // Store original Marathi type
      price: price || 0,
      is_active: true,
      sort_order: num,
      created_at: now,
    };

    try {
      await ddb.send(new PutCommand({
        TableName: TABLE,
        Item: item,
        ConditionExpression: 'attribute_not_exists(medicine_id)',
      }));
      created++;
      if (created % 20 === 0) console.log(`  ✓ Seeded ${created} medicines...`);
    } catch (err) {
      if (err.name === 'ConditionalCheckFailedException') {
        skipped++;
      } else {
        console.error(`✗ Error on medicine #${num} "${nameMr}":`, err.message);
      }
    }
  }

  console.log(`\n✅ Done! Created: ${created}, Skipped (already exist): ${skipped}`);
  console.log(`Total medicines seeded: ${created + skipped} / ${medicines.length}`);
}

console.log(`🌱 Seeding ${medicines.length} Ayurvedic medicines to ${TABLE}...\n`);
seed().catch(console.error);
